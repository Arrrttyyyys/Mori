const assert = require('node:assert/strict');
const { reviewedSessionContext } = require('/tmp/mori-continuity-test/session-continuity.js');
const summary=(id,text='The person talked about gardening.')=>({id,topic:'Gardening',summary:text,updated_at:'2026-10-01T12:00:00Z'});
const review=(id,decision='approved',correction=null,created_at='2026-10-02T12:00:00Z')=>({resource_id:id,decision,correction,created_at});
const safe=text=>!text.toLowerCase().includes('restricted');
assert.equal(reviewedSessionContext([summary('a')],[],safe),'');
assert.equal(reviewedSessionContext([summary('a')],[review('a','rejected')],safe),'');
assert.equal(reviewedSessionContext([summary('a')],[review('a','approved',null,'2026-09-30')],safe),'');
assert.equal(reviewedSessionContext([summary('a')],[review('a'),review('a','sensitive',null,'2026-10-03')],safe),'');
assert.equal(reviewedSessionContext([summary('a','restricted detail')],[review('a')],safe),'');
const corrected=JSON.parse(reviewedSessionContext([summary('a','incorrect account')],[review('a','corrected','A corrected account.')],safe));
assert.equal(corrected[0].account,'A corrected account.');
assert.equal(corrected[0].source,'caregiver-corrected session account');
assert.equal(reviewedSessionContext([summary('a')],[review('a','corrected',' ')],safe),'');
const ids=['a','b','c','d'];
const limited=reviewedSessionContext(ids.map(id=>summary(id,'x'.repeat(10000))),ids.map(id=>review(id)),safe);
assert.equal(JSON.parse(limited).length,3);
assert.ok(limited.length<2000);
assert.ok(JSON.parse(limited).every(e=>e.account.length===450));
console.log('Session continuity checks passed: review gates, corrections, withdrawals, current restrictions, revision freshness and context limits.');
